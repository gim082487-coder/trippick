def patch(fname, pairs):
    p = G / fname
    t = p.read_text(encoding="utf-8")
    for old, new in pairs:
        if t.count(old) == 0:
            print(f"  !! not found in {fname}: {old[:60]}")
            continue
        t = t.replace(old, new)
    p.write_text(t, encoding="utf-8")
    print(f"  ok {fname}")

